def A(text: str) -> dict[str, str]:
    return {"role": "assistant", "content": text}


def U(text: str) -> dict[str, str]:
    return {"role": "user", "content": text}


def fact(fid: str, kind: str, statement: str, probe: str, check: dict[str, Any],
         answer: str = "", trap: str = "") -> dict[str, Any]:
    return {
        "id": fid, "kind": kind, "statement": statement, "probe": probe,
        "check": check, "answer": answer, "trap": trap,
    }


def fc(path: str, contains: str, not_contains: str | None = None) -> dict[str, Any]:
    args: dict[str, Any] = {"path": path, "contains": contains}
    if not_contains is not None:
        args["not_contains"] = not_contains
    return {"fn": "file_content", "args": args}


def LSE(path: str, equals: list[str]) -> dict[str, Any]:
    return {"fn": "line_set_equals", "args": {"path": path, "equals": equals}}


def COC(code: str, contains: str) -> dict[str, Any]:
    return {"fn": "command_output_contains", "args": {
        "command": ["python", "-c", code], "contains": contains, "allowed_commands": ["python"]}}


