def build(case: dict[str, Any]) -> dict[str, Any]:
    fmt = {
        "helper": case["helper"],
        "plan": case["plan"],
        "filename": case["filename"],
        "bucket": case["bucket"],
        "report_file": case["report_file"],
        "bug": case["bug"],
        "fix_file": case["fix_file"],
        "decision": case["decision"],
        "constraint": case["constraint"],
        "module_rel": f"multiagent/{case['module']}.py",
        "deprecated_file": "src/cleanup.py",
        "helper_file": f"multiagent/{case['module']}.py",
        "plan_file": "multiagent/coordinator.py",
    }
    history = [{k: str(v).format(**fmt) for k, v in msg.items()} for msg in case["history"]]

    prefix = case["prefix"]
    # The workspace assignment rendered inside the continuation task.
    cont = (
        "继续基于 multiagent_repo 工作：第 4 步的批量聚合还没接上，需要修复。"
        "把以下 5 条信息逐行写进 `" + ANSWER_FILE + "`（每行 `<id>=<答案>`，A5 写 `A5=是`）：\n"
        "A1={helper_file}\n"
        "A2={plan}\n"
        "A3={fix_file}\n"
        "A4={decision}\n"
        "A5=是\n"
        "然后把 `{filename}` 追加一行 `" + prefix + "1`，"
        "再运行 `python -m pytest tests -q`，把通过的条数写成 `<N> passed` "
        "追加到同一行之后。"
    ).format(**fmt)

    # A4's expected answer is a stable, unambiguous slice of the decision: its
    # opening clause up to the first comma. The full decision text is prose and
    # pinning it verbatim would grade phrasing, not retention.
    decision_tag = case["decision"].split("，")[0]
    module_rel = f"multiagent/{case['module']}.py"
    facts = [
        fact(
            "A1", "file-path",
            statement=f"{case['helper']} 位于 {module_rel}",
            probe="A1：承载本次工具函数的源文件路径是什么？",
            check=fc(ANSWER_FILE, r"(?m)^A1=\s*" + re.escape(module_rel)),
            # The slug deliberately does not contain the function name, so this
            # fact is a real needle: history retention is the only way to it.
            answer=module_rel,
            trap=f"multiagent/{case['helper']}.py",
        ),
        fact(
            "A2", "symbol-name",
            statement=f"调用方符号是 {case['plan']}",
            probe="A2：第一段历史里提到的调用方符号名是什么？",
            check=fc(ANSWER_FILE, r"(?m)^A2=\s*" + case["plan"] + r"\s*$"),
            answer=case["plan"],
            trap=case["helper"],
        ),
        fact(
            "A3", "error-cause",
            statement=f"{case['bug']}",
            probe="A3：第 6 轮确定的那处已知原因，修复点在哪个文件？",
            check=fc(ANSWER_FILE, r"(?m)^A3=\s*" + re.escape(case["fix_file"]) + r"\s*$"),
            answer=case["fix_file"],
            trap=fmt["plan_file"],
        ),
        fact(
            "A4", "design-decision",
            statement=case["decision"],
            probe="A4：第 8 轮确定的设计决策，要点是什么？",
            check=fc(ANSWER_FILE, r"(?m)^A4=\s*" + re.escape(decision_tag)),
            answer=decision_tag,
            trap=case["fix_file"],
        ),
        fact(
            "A5", "open-constraint",
            statement=(
                # {report_file} 是文件名, {constraint} 是自带句号的完整约束句,
                # {deprecated_file} 是路径. 旧模板写成 "{report_file} 与 {constraint}；",
                # 「与」是连接词却接了完整句子, 且 constraint 自带的句号与模板的
                # 「；」连成 "。；" -- 20 条全中, 占 100 条事实的 20%.
                f"未完成步骤：{case['report_file']} 还没产出。约束：{case['constraint']}"
                f"废弃模块 {fmt['deprecated_file']} 不得改动。"
            ),
            probe="A5：那条未完成的约束现在还成立吗？",
            check=fc(ANSWER_FILE, r"(?m)^A5=是"),
            answer="是",
            trap="否",
        ),
    ]

    return {
        "id": case["id"],
        "type": "compression",
        "fixture": FIXTURE,
        "tags": ["compression"],
        "max_turns": 14,
        "history": history,
        "key_facts": facts,
        "continuation_task": cont,
        "probe_question": PROBE_QUESTION,
        "compaction_note": "压缩时务必保留尚未完成的步骤与仍然成立的约束，不要只保留已完成的部分。",
        "checks": [
            FILLED,
            # The suite must be GREEN after the fix: the artifact gate is the
            # agent's own corrected run, and a lingering failure means the fix
            # did not land. (The fixture starts red -- pinned by
            # `test_coordinator_test_suite_passes_on_the_fixture`.)
            #
            # 这条是承重判分, 不要当成"题面没说所以多余"删掉: 变异验证过
            # 它抓住"部分修复"(merge 修好但顺序仍错 -> 1 failed, 3 passed),
            # 也抓住"把测试改成 assert True"这种伪造。比单独看源码强,
            # 因为它要求的是修好之后真的跑绿。
            {
                "fn": "command_output_contains",
                "args": {**PYTEST_CMD, "contains": f"{FIXED_PASSED} passed"},
            },
            {
                "fn": "file_content",
                "args": {"path": "tests/test_coordinator.py", "contains": "def test_"},
            },
            COC(
                "chunks=[[{'key':'a','value':1},{'key':'b','value':2}],"
                "[{'key':'a','value':3}],[{'key':'c','value':4}]];"
                "m={r['key']:r for c in chunks for r in c};"
                "print('MERGED_COUNT=' + str(len(m)))",
                f"MERGED_COUNT={MERGED_ROWS}",
            ),
            fc(fmt["deprecated_file"], r"DEPRECATED", r"^\s*def\s+"),
            fc("multiagent/coordinator.py", r"并发度默认 2", r"max_concurrency\s*=\s*3"),
        ],
        "probe_checks": [],
        "decision_note": case["decision"],
        "threshold": case["threshold"],
    }


def main() -> None:
    lines = [json.dumps(build(c), ensure_ascii=False) for c in CASES]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(lines)} cases -> {OUT}")


if __name__ == "__main__":
    main()
